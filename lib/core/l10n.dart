/// Тилди башкарат (кыргызча / орусча). Тандоо телефондо сакталат.
class LocaleController extends ChangeNotifier {
  LocaleController._();
  static final LocaleController instance = LocaleController._();

  Locale _locale = const Locale('ky');
  Locale get locale => _locale;

  Future<void> load() async {
    final c = await Prefs.language();
    if (c == 'ky' || c == 'ru') _locale = Locale(c!);
  }

  Future<void> set(String code) async {
    if (code == _locale.languageCode) return;
    _locale = Locale(code);
    notifyListeners();
    await Prefs.setLanguage(code);
  }
}

/// `context.tr('ачкыч')` — тексттин учурдагы тилдеги котормосу.
/// Тил алмашканда бул методду колдонгон бардык экрандар өзү кайра тартылат.
extension Tr on BuildContext {
  String tr(String key, [Map<String, String> args = const {}]) {
    final code = Localizations.localeOf(this).languageCode;
    var s = _strings[key]?[code] ?? _strings[key]?['ky'] ?? key;
    args.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }

  /// Котормо жок болсо [fallback] кайтарат.
  String trOr(String key, String fallback) {
    final code = Localizations.localeOf(this).languageCode;
    return _strings[key]?[code] ?? fallback;
  }

  String statusText(OrderStatus s) => tr(switch (s) {
        OrderStatus.open => 'st_open',
        OrderStatus.waiting => 'st_waiting',
        OrderStatus.toPickup => 'st_topickup',
        OrderStatus.onTheWay => 'st_onway',
        OrderStatus.delivered => 'st_delivered',
      });

  String colorLabel(String name) => trOr('color_$name', name);
}

